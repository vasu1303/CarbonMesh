import { z } from 'zod'
import {
  agentContextSchema,
  decimal,
  hash,
  timestamp,
  uuid,
} from '@/features/agents/schemas'

const count = z.number().int().nonnegative()
export const runStateSchema = z.enum([
  'running',
  'success',
  'needs_clarification',
  'no_data',
  'validation_error',
  'unsupported',
  'policy_blocked',
  'provider_unavailable',
  'no_feasible_option',
  'no_feasible_candidate',
  'no_feasible_window',
  'failed_validation',
  'validation_failed',
  'budget_exhausted',
  'approval_required',
  'approval_invalidated',
  'stale',
  'completed',
  'failed',
])
const workflow = z.enum([
  'planning',
  'measurement',
  'assurance',
  'procurement',
  'dispatch',
  'cross_module',
  'four_module',
  'unsupported',
])
export const eventNames = [
  'run.started',
  'node.started',
  'node.completed',
  'node.failed',
  'stage.started',
  'stage.completed',
  'tool.started',
  'tool.completed',
  'tool.failed',
  'provider.started',
  'provider.completed',
  'provider.failed',
  'provider.cache_hit',
  'validation.warning',
  'fact.created',
  'clarification.required',
  'approval.required',
  'run.resumed',
  'run.resume_blocked',
  'run.resume_resolved',
  'run.completed',
  'run.stopped',
] as const
export const eventDataSchema = z.object({
  occurred_at: timestamp.optional(),
  sequence: count.optional(),
  run_id: uuid.optional(),
  step_type: z.string().nullish(),
  status: z.string().nullish(),
  graph_name: z.string().nullish(),
  node_name: z.string().nullish(),
  tool_name: z.string().nullish(),
  stage: z.string().nullish(),
  tool: z.string().nullish(),
  provider: z.string().nullish(),
  model_id: z.string().nullish(),
  input_tokens: count.nullish(),
  output_tokens: count.nullish(),
  cached_input_tokens: count.nullish(),
  retry_count: count.nullish(),
  latency_ms: count.nullish(),
  elapsed_ms: count.nullish(),
  cache_hit: z.boolean().nullish(),
  error_code: z.string().nullish(),
  message: z.string().nullish(),
  terminal_state: runStateSchema.optional(),
  ledger_event_id: uuid.nullish(),
  fact_id: uuid.nullish(),
})
export const eventSchema = z.object({
  sequence: count,
  name: z.enum(eventNames),
  occurred_at: timestamp,
  data: eventDataSchema,
})
export type RunEvent = z.infer<typeof eventSchema>
export const interruptSchema = z.object({
  interrupt_id: uuid,
  sequence: z.number().int().positive(),
  kind: z.enum(['clarification', 'approval']),
  status: z.enum(['pending', 'resumed', 'resolved', 'stale']),
  analysis_signature: hash,
  missing_fields: z.array(z.string()),
  approval_id: uuid.nullish(),
  target_type: z.string().nullish(),
  target_id: uuid.nullish(),
  preview_hash: hash.nullish(),
  expires_at: timestamp.nullish(),
})
export const telemetrySchema = z.object({
  trace_id: z.string(),
  analysis_signature: hash,
  orchestrator_version: z.string(),
  provider: z.enum(['none', 'openai', 'gemini', 'anthropic', 'openrouter']),
  provider_status: z.enum([
    'not_requested',
    'configured',
    'completed',
    'unavailable',
    'blocked',
  ]),
  model_id: z.string().nullable(),
  model_calls: count,
  input_tokens: count,
  output_tokens: count,
  cached_input_tokens: count,
  context_tokens: count,
  tool_calls: count,
  retry_count: count,
  repairs: count,
  api_calls: count,
  cache_hits: count,
  external_cache_hits: count,
  rows_processed: count,
  evidence_chunks_retrieved: count,
  elapsed_ms: count,
  estimated_energy_wh: decimal.nullable(),
  estimated_co2e_g: decimal.nullable(),
  sustainability_method: z.string().nullable(),
  sustainability_assumptions: z.record(z.string(), z.string()),
  execution_attempts: count,
  stage_timings: z.array(z.object({ stage: z.string(), elapsed_ms: count })),
  events: z.array(eventSchema),
})
export const executionPlanSchema = z.object({
  version: z.literal('carbonmesh.execution-plan.v1'),
  profile: z.string(),
  context_tools: z.array(z.string()),
  expected_model_calls: count,
  stages: z.array(
    z.object({
      stage_id: z.string(),
      module: z.string(),
      depends_on: z.array(z.string()),
      tool_names: z.array(z.string()),
      requires_human_approval: z.boolean(),
    }),
  ),
})
export const legacyPlanSchema = z.object({
  version: z.literal('orchestrator.initial'),
  steps: z.array(
    z.object({
      id: z.string(),
      title: z.string(),
      responsibility: z.string(),
      status: z.string(),
      tool_ids: z.array(z.string()),
    }),
  ),
})
export const runSchema = z.object({
  run_id: uuid,
  trace_id: z.string(),
  workflow,
  stage: z.string(),
  terminal_state: runStateSchema,
  context: agentContextSchema.extend({
    workflow,
    actor_role: z.string(),
    request_hash: hash,
    analysis_signature: hash,
  }),
  plan: z.record(z.string(), z.unknown()).nullable(),
  facts: z.array(
    z.object({
      fact_id: uuid,
      metric_key: z.string(),
      display_value: z.string(),
      ledger_event_id: uuid,
    }),
  ),
  judgments: z.array(
    z.object({
      kind: z.literal('workflow_classification'),
      value: workflow,
      basis: z.enum([
        'deterministic_keyword_rules',
        'structured_model_plan',
        'policy_gate',
      ]),
      matched_terms: z.array(z.string()),
    }),
  ),
  telemetry: telemetrySchema,
  approval_requirement: z.object({
    required: z.boolean(),
    approval_id: uuid.nullable(),
    recommendation_id: uuid.nullable(),
    preview_hash: hash.nullable(),
  }),
  recommendation: z
    .object({
      scenario_id: uuid,
      recommendation_id: uuid,
      recommended_product_id: uuid,
      status: z.string(),
      projected_footprint_kgco2e: decimal,
      avoided_kgco2e: decimal,
      reduction_pct: decimal,
      cost_delta_pct: decimal,
      lead_time_delta_days: z.number().int(),
      payload_hash: hash,
      analysis_signature: hash,
      ledger_event_id: uuid,
    })
    .nullable(),
  pending_interrupt: interruptSchema.nullable(),
  message: z.string().nullable(),
  missing_fields: z.array(z.string()),
  unsupported_reason: z.string().nullable(),
  unsupported_items: z.array(z.string()),
  error_code: z.string().nullable(),
  started_at: timestamp,
  completed_at: timestamp.nullable(),
})
export type AgentRun = z.infer<typeof runSchema>
export const resumeResultSchema = z.object({
  run_id: uuid,
  trace_id: z.string(),
  terminal_state: runStateSchema,
  resumed: z.boolean(),
  idempotent_replay: z.boolean(),
})
export const approvalObserverSchema = z.object({
  id: uuid,
  company_id: uuid,
  status: z.string(),
  target_type: z.string(),
  target_id: uuid,
  preview_hash: hash,
  analysis_signature: hash,
  expired: z.boolean(),
  preview_current: z.boolean(),
  decided_by: uuid.nullable(),
  decided_at: timestamp.nullable(),
  ledger_event_id: uuid.nullable(),
})
const assumptionsSchema = z.object({
  method: z.string(),
  version: z.string(),
  energy_wh_per_1k_tokens: decimal,
  grid_intensity_gco2e_per_kwh: decimal,
  caveat: z.string(),
  functional_unit: z.string(),
  region_basis: z.string(),
  omitted_footprint: z.string(),
  uncertainty: z.string(),
  benefit_basis: z.string(),
})
export const sustainabilitySchema = z.object({
  company_id: uuid,
  from_time: timestamp.nullable(),
  to_time: timestamp.nullable(),
  run_count: count,
  completed_run_count: count,
  interrupted_run_count: count,
  provider_call_count: count,
  tool_call_count: count,
  input_tokens: count,
  output_tokens: count,
  cached_input_tokens: count,
  retry_count: count,
  cache_hits: count,
  latency_ms: count,
  estimated_energy_wh: decimal,
  estimated_co2e_g: decimal,
  proxy_coverage_runs: count,
  assumptions: assumptionsSchema,
  external_api_calls: count,
  business_benefit_kgco2e: decimal,
  benefit_to_footprint_ratio: decimal.nullable(),
  benefit_facts: z.array(
    z.object({
      target_type: z.string(),
      target_id: uuid,
      ledger_event_id: uuid,
      avoided_kgco2e: decimal,
    }),
  ),
  assumption_coverage_runs: count,
  assumption_sets: z.array(assumptionsSchema),
})
